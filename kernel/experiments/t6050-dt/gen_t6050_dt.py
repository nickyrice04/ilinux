#!/usr/bin/env python3
"""Generate a DRAFT minimal Linux device tree for Apple t6050 (M5 Max) from
the sanitized macOS ADT capture (hardware/adt/adt-sanitized.json).

Scope mirrors the Asahi "minimal" bring-up DTs (e.g. t8132, 2026-07): CPUs and
caches, timer, AIC3, watchdog, UART, I2C, pinctrl.  Power domains (PMGR),
cpufreq, DARTs and everything behind coprocessors are left out.

STATUS: untested.  Booting needs m1n1 support for t6050, which does not exist.
Values marked HYPOTHESIS must be confirmed on hardware before any use.

Usage: gen_t6050_dt.py ADT_JSON OUTDIR
"""
import json
import sys

AIC_CORE_SIZE = 0x1CC000


def load(path):
    tree = json.load(open(path))
    nodes = {}

    def walk(n):
        nodes[n["path"].replace("/Root/device-tree", "") or "/"] = n["values"]
        for c in n["children"]:
            walk(c)
    walk(tree["children"][0])
    return nodes


def u32s(v):
    if isinstance(v, int):
        return [v]
    return [int(x, 16) if isinstance(x, str) else x for x in v]


def arm_io_ranges(nodes):
    w = u32s(nodes["/arm-io"]["ranges"])
    out = []
    for i in range(0, len(w) - 5, 6):
        child = w[i] | (w[i + 1] << 32)
        parent = w[i + 2] | (w[i + 3] << 32)
        size = w[i + 4] | (w[i + 5] << 32)
        out.append((child, parent, size))
    return out


def translate(ranges, addr):
    for child, parent, size in ranges:
        if child <= addr < child + size:
            return parent + (addr - child)
    raise ValueError("address %#x not covered by arm-io ranges" % addr)


def reg_of(nodes, path, index=0):
    r = nodes[path]["reg"][index]
    return int(r["addr"], 16), int(r["size"], 16)


def cells(addr, size):
    return "<0x%x 0x%08x 0x%x 0x%x>" % (addr >> 32, addr & 0xFFFFFFFF, size >> 32, size & 0xFFFFFFFF)


def irqs(nodes, path):
    return u32s(nodes[path].get("interrupts", []))


def main():
    adt, outdir = sys.argv[1], sys.argv[2]
    nodes = load(adt)
    rng = arm_io_ranges(nodes)
    cpus = sorted((p for p in nodes if p.startswith("/cpus/cpu")),
                  key=lambda p: nodes[p]["cpu-id"])
    L = []
    a = L.append
    a("// SPDX-License-Identifier: GPL-2.0+ OR MIT")
    a("/*")
    a(" * Apple t6050 \"M5 Max\" SoC - DRAFT minimal device tree.")
    a(" *")
    a(" * Generated by kernel/experiments/t6050-dt/gen_t6050_dt.py from a sanitized")
    a(" * macOS ADT capture of a Mac17,6 (J716c).  UNTESTED: requires m1n1 support")
    a(" * for t6050.  See README.md in this directory for open questions.")
    a(" */")
    a("")
    a("#include <dt-bindings/interrupt-controller/apple-aic.h>")
    a("#include <dt-bindings/interrupt-controller/irq.h>")
    a("#include <dt-bindings/pinctrl/apple.h>")
    a("")
    a("/ {")
    a('\tcompatible = "apple,t6050", "apple,arm-platform";')
    a("\t#address-cells = <2>;")
    a("\t#size-cells = <2>;")
    a("")
    a("\tcpus {")
    a("\t\t#address-cells = <2>;")
    a("\t\t#size-cells = <0>;")
    a("")
    a("\t\tcpu-map {")
    clusters = {}
    for p in cpus:
        clusters.setdefault(nodes[p]["cluster-id"], []).append(p)
    labels = {}
    for cid in sorted(clusters):
        a("\t\t\tcluster%d {" % cid)
        for i, p in enumerate(clusters[cid]):
            v = nodes[p]
            ctype = v["cluster-type"][0].lower()
            lab = "cpu_%s%d" % (ctype, sum(1 for q in cpus[:cpus.index(p)]
                                           if nodes[q]["cluster-type"] == v["cluster-type"]))
            labels[p] = lab
            a("\t\t\t\tcore%d {" % i)
            a("\t\t\t\t\tcpu = <&%s>;" % lab)
            a("\t\t\t\t};")
        a("\t\t\t};")
    a("\t\t};")
    a("")
    for p in cpus:
        v = nodes[p]
        mpidr = int(v["reg"][0]["addr"], 16)
        ctype = v["cluster-type"][0].lower()
        a("\t\t/* ADT %s: cluster %d type %s (%s); MPIDR below is the ADT reg value -"
          % (p.split("/")[-1], v["cluster-id"], v["cluster-type"][0], v["compatible"][0]))
        a("\t\t * HYPOTHESIS: real MPIDR may carry extra Aff2 bits (m1n1 must confirm). */")
        a("\t\t%s: cpu@%x {" % (labels[p], mpidr))
        a('\t\t\tcompatible = "apple,sotra-%s"; /* placeholder: needs DT binding */' % ctype)
        a('\t\t\tdevice_type = "cpu";')
        a("\t\t\treg = <0x0 0x%x>;" % mpidr)
        a('\t\t\tenable-method = "spin-table";')
        a("\t\t\tcpu-release-addr = <0 0>; /* filled in by m1n1 */")
        a("\t\t\tnext-level-cache = <&l2_cache_%d>;" % v["cluster-id"])
        a("\t\t};")
        a("")
    for cid in sorted(clusters):
        size = nodes[clusters[cid][0]]["l2-cache-size"]
        a("\t\tl2_cache_%d: l2-cache-%d {" % (cid, cid))
        a('\t\t\tcompatible = "cache";')
        a("\t\t\tcache-level = <2>;")
        a("\t\t\tcache-unified;")
        a("\t\t\tcache-size = <0x%x>;" % size)
        a("\t\t};")
        a("")
    a("\t};")
    a("")
    a("\ttimer {")
    a('\t\tcompatible = "arm,armv8-timer";')
    a("\t\tinterrupt-parent = <&aic>;")
    a('\t\tinterrupt-names = "phys", "virt", "hyp-phys", "hyp-virt";')
    a("\t\tinterrupts = <AIC_FIQ AIC_TMR_GUEST_PHYS IRQ_TYPE_LEVEL_HIGH>,")
    a("\t\t\t     <AIC_FIQ AIC_TMR_GUEST_VIRT IRQ_TYPE_LEVEL_HIGH>,")
    a("\t\t\t     <AIC_FIQ AIC_TMR_HV_PHYS IRQ_TYPE_LEVEL_HIGH>,")
    a("\t\t\t     <AIC_FIQ AIC_TMR_HV_VIRT IRQ_TYPE_LEVEL_HIGH>;")
    a("\t};")
    a("")
    a("\tclkref: clock-ref {")
    a('\t\tcompatible = "fixed-clock";')
    a("\t\t#clock-cells = <0>;")
    a("\t\tclock-frequency = <%d>;" % nodes["/"]["clock-frequency"])
    a('\t\tclock-output-names = "clkref";')
    a("\t};")
    a("")
    a("\tsoc: soc {")
    a('\t\tcompatible = "simple-bus";')
    a("\t\t#address-cells = <2>;")
    a("\t\t#size-cells = <2>;")
    a("\t\tranges;")
    a("\t\tnonposted-mmio;")
    a("")
    # AIC3
    aic_child, aic_size = reg_of(nodes, "/arm-io/aic")
    aic = translate(rng, aic_child)
    a("\t\t/* ADT aic: compatible aic,3, reg size 0x%x (same as t8132's AIC3). */" % aic_size)
    a("\t\taic: interrupt-controller@%x {" % aic)
    a('\t\t\tcompatible = "apple,t6050-aic3", "apple,t8122-aic3";')
    a("\t\t\t#interrupt-cells = <3>;")
    a("\t\t\tinterrupt-controller;")
    iack = u32s(nodes["/arm-io/aic"].get("aic-iack-offset", [0x40000]))[0]
    a("\t\t\treg = %s,\n\t\t\t      %s;" % (cells(aic, aic_size), cells(aic + iack, 0x4000)))
    a('\t\t\treg-names = "core", "event";')
    a("\t\t\t/* event region = core + ADT aic-iack-offset (0x%x), matching the" % iack)
    a("\t\t\t * core+0x40000 layout Asahi uses for t8122/t8132 AIC3. */")
    pm, pp = [labels[p] for p in cpus if nodes[p]["cluster-type"][0] == "M"], \
        [labels[p] for p in cpus if nodes[p]["cluster-type"][0] == "P"]
    a("\t\t\taffinities {")
    a("\t\t\t\tm-core-pmu-affinity {")
    a("\t\t\t\t\tapple,fiq-index = <AIC_CPU_PMU_E>;")
    a("\t\t\t\t\tcpus = <%s>;" % " ".join("&" + x for x in pm))
    a("\t\t\t\t};")
    a("\t\t\t\tp-core-pmu-affinity {")
    a("\t\t\t\t\tapple,fiq-index = <AIC_CPU_PMU_P>;")
    a("\t\t\t\t\tcpus = <%s>;" % " ".join("&" + x for x in pp))
    a("\t\t\t\t};")
    a("\t\t\t};")
    a("\t\t};")
    a("")
    # Watchdog
    w_child, w_size = reg_of(nodes, "/arm-io/wdt")
    w = translate(rng, w_child)
    a("\t\twdt: watchdog@%x {" % w)
    a('\t\t\tcompatible = "apple,t6050-wdt", "apple,t8103-wdt";')
    a("\t\t\treg = %s;" % cells(w, w_size))
    a("\t\t\tclocks = <&clkref>;")
    a("\t\t\tinterrupt-parent = <&aic>;")
    a("\t\t\tinterrupts = <AIC_IRQ %d IRQ_TYPE_LEVEL_HIGH>;" % irqs(nodes, "/arm-io/wdt")[0])
    a("\t\t};")
    a("")
    # Pinctrl / GPIO controllers
    for path, lab in (("/arm-io/gpio0", "pinctrl_ap"), ("/arm-io/aop-gpio0", "pinctrl_aop"),
                      ("/arm-io/nub-gpio0", "pinctrl_nub")):
        if path not in nodes or "reg" not in nodes[path]:
            continue
        c, s = reg_of(nodes, path)
        addr = translate(rng, c)
        npins = nodes[path].get("#gpio-pins")
        a("\t\t%s: pinctrl@%x {" % (lab, addr))
        a('\t\t\tcompatible = "apple,t6050-pinctrl", "apple,t8103-pinctrl";')
        a("\t\t\treg = %s;" % cells(addr, s))
        a("\t\t\tgpio-controller;")
        a("\t\t\t#gpio-cells = <2>;")
        if npins:
            a("\t\t\tgpio-ranges = <&%s 0 0 %d>;" % (lab, npins))
            a("\t\t\tapple,npins = <%d>;" % npins)
        a("\t\t\tinterrupt-controller;")
        a("\t\t\t#interrupt-cells = <2>;")
        a("\t\t\tinterrupt-parent = <&aic>;")
        ir = irqs(nodes, path)
        a("\t\t\tinterrupts = %s;" % ",\n\t\t\t\t     ".join(
            "<AIC_IRQ %d IRQ_TYPE_LEVEL_HIGH>" % i for i in ir))
        a("\t\t\t/* TODO: power-domains (PMGR not yet described). */")
        a("\t\t};")
        a("")
    # I2C
    for i in range(16):
        path = "/arm-io/i2c%d" % i
        if path not in nodes:
            continue
        c, s = reg_of(nodes, path)
        addr = translate(rng, c)
        a("\t\ti2c%d: i2c@%x {" % (i, addr))
        a('\t\t\tcompatible = "apple,t6050-i2c", "apple,t8103-i2c";')
        a("\t\t\treg = %s;" % cells(addr, s))
        a("\t\t\tclocks = <&clkref>;")
        a("\t\t\tinterrupt-parent = <&aic>;")
        a("\t\t\tinterrupts = <AIC_IRQ %d IRQ_TYPE_LEVEL_HIGH>;" % irqs(nodes, path)[0])
        a("\t\t\t#address-cells = <0x1>;")
        a("\t\t\t#size-cells = <0x0>;")
        a('\t\t\tstatus = "disabled";')
        a("\t\t};")
        a("")
    # UART
    c, s = reg_of(nodes, "/arm-io/uart0")
    addr = translate(rng, c)
    a("\t\tserial0: serial@%x {" % addr)
    a('\t\t\tcompatible = "apple,s5l-uart";')
    a("\t\t\treg = %s;" % cells(addr, s))
    a("\t\t\treg-io-width = <4>;")
    a("\t\t\tinterrupt-parent = <&aic>;")
    a("\t\t\tinterrupts = <AIC_IRQ %d IRQ_TYPE_LEVEL_HIGH>;" % irqs(nodes, "/arm-io/uart0")[0])
    a("\t\t\tclocks = <&clkref>, <&clkref>;")
    a('\t\t\tclock-names = "uart", "clk_uart_baud0";')
    a('\t\t\tstatus = "disabled";')
    a("\t\t};")
    a("\t};")
    a("};")
    open(outdir + "/t6050.dtsi", "w").write("\n".join(L) + "\n")

    root = nodes["/"]
    B = []
    b = B.append
    b("// SPDX-License-Identifier: GPL-2.0+ OR MIT")
    b("/*")
    b(" * Apple MacBook Pro (16-inch, M5 Max), %s / %s - DRAFT, untested."
      % (root["model"][0], root["target-type"][0]))
    b(" */")
    b("")
    b("/dts-v1/;")
    b("")
    b('#include "t6050.dtsi"')
    b("")
    b("/ {")
    b('\tcompatible = "apple,%s", "apple,t6050", "apple,arm-platform";'
      % root["target-type"][0].lower())
    b('\tmodel = "Apple MacBook Pro (16-inch, M5 Max)";')
    b("")
    b("\taliases {")
    b("\t\tserial0 = &serial0;")
    b("\t};")
    b("")
    b("\tchosen {")
    b("\t\t#address-cells = <2>;")
    b("\t\t#size-cells = <2>;")
    b("\t\tranges;")
    b('\t\tstdout-path = "serial0";')
    b("\t};")
    b("")
    b("\tmemory@10000000000 {")
    b('\t\tdevice_type = "memory";')
    b("\t\treg = <0x100 0 0x2 0>; /* placeholder; m1n1 fills in the real map */")
    b("\t};")
    b("};")
    b("")
    b("&serial0 {")
    b('\tstatus = "okay";')
    b("};")
    open(outdir + "/t6050-%s.dts" % root["target-type"][0].lower(), "w").write("\n".join(B) + "\n")
    print("wrote t6050.dtsi and board dts (%d cpus, %d clusters)" % (len(cpus), len(clusters)),
          file=sys.stderr)


if __name__ == "__main__":
    main()
