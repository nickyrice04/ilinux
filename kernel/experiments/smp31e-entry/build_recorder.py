"""Build an OFFLINE RAM-patch proposal; never modifies the input or a target.

The independent guest assembler must reproduce recorder.bin before review.
Only this directory's ignored out/ may receive generated bytes. No transport,
native adapter, code execution, permission changes or boot-object operations.
"""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import stat
import struct
import tempfile

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('entry_audit', HERE / 'audit.py')
audit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(audit)
need = audit.need
ENTRY = 0x8fc
RESUME = 0x900
CODE_START, CODE_END = 0xa00, 0xc00
RECORD, RECORD_END = 0x90a40, 0x90a80
ORIGINAL_MOV = 0x528009e0


def branch(pc, target, condition=None):
    delta = target - pc
    bits = 26 if condition is None else 19
    need(delta % 4 == 0 and -(1 << (bits+1)) <= delta < (1 << (bits+1)),
         'branch_out_of_range')
    immediate = (delta // 4) & ((1 << bits)-1)
    if condition is None:
        return 0x14000000 | immediate
    need(condition in (0, 1), 'unsupported_condition')
    return 0x54000000 | immediate << 5 | condition


def adrp(pc, target, register=0):
    delta = ((target & ~4095) - (pc & ~4095)) // 4096
    need(-(1 << 20) <= delta < (1 << 20), 'adrp_out_of_range')
    immediate = delta & ((1 << 21)-1)
    return 0x90000000 | (immediate & 3) << 29 | (immediate >> 2) << 5 | register


def adjacent_add_offset(instruction, base_register):
    """Decode 64-bit ADD immediate with either architectural shift, 0 or 12."""
    if instruction & 0xff800000 != 0x91000000 or (instruction >> 5) & 31 != base_register:
        return None
    return ((instruction >> 10) & 4095) << (12 if instruction & (1 << 22) else 0)


def program():
    """Independent encodings for the intentionally small recorder.S subset."""
    instructions, labels = [], {}
    def label(name):
        labels[name] = CODE_START + len(instructions)*4
    def emit(word):
        instructions.append(word)
    def mov(value):
        need(0 <= value < 65536, 'mov_value')
        emit(0xd2800008 | value << 5)  # MOVZ X8,#value
    def jump(name, condition=None):
        emit(('branch', name, condition))
    def phase(value):
        emit(0xd5033f9f); mov(value); emit(0xf9000008); emit(0xd5033f9f)
    emit(0xd53800a8)              # MRS X8,MPIDR_EL1
    emit(0xd3405d08)              # UBFX X8,X8,#0,#24
    emit(0xd2800020)              # MOVZ X0,#1
    emit(0xf2a00080)              # MOVK X0,#4,LSL#16
    emit(0xeb00011f)              # CMP X8,X0
    jump('replay', 1)
    emit(('adrp', RECORD))
    emit(0x91000000 | (RECORD & 4095) << 10)  # ADD X0,X0,#low12
    emit(0xf9000808)              # STR X8,[X0,#16]
    phase(1)
    emit(0xd5384248)              # MRS X8,CurrentEL
    emit(0xf9000408)              # STR X8,[X0,#8]
    for level in (1, 2, 3):
        emit(0xf100011f | (level*4) << 10)  # CMP X8,#level*4
        jump('el'+str(level), 0)
    phase(255)
    jump('replay')
    for level, mrs in [(1, 0xd5381008), (2, 0xd53c1008), (3, 0xd53e1008)]:
        label('el'+str(level))
        phase(2)
        emit(mrs)
        jump('sctlr_done')
    label('sctlr_done')
    emit(0xf9000c08)              # STR X8,[X0,#24]
    phase(3)
    label('replay')
    emit(ORIGINAL_MOV)
    emit(('branch', RESUME, None))
    words = []
    for index, instruction in enumerate(instructions):
        pc = CODE_START + index*4
        if isinstance(instruction, tuple):
            if instruction[0] == 'adrp':
                instruction = adrp(pc, instruction[1])
            else:
                _, target, condition = instruction
                instruction = branch(pc, labels[target] if isinstance(target,str) else target,
                                     condition)
        words.append(instruction)
    need(CODE_START + 4*len(words) <= CODE_END, 'recorder_too_large')
    return struct.pack('<'+'I'*len(words), *words), labels


def region_audit(image, symbols):
    records = [(int(value,16), kind, name) for value,kind,name in
               (line.split() for line in symbols.decode().splitlines()
                if len(line.split()) == 3)]
    named = {name:value for value,_,name in records}
    ranges = [(CODE_START,CODE_END),(RECORD,RECORD_END)]
    for start,end in ranges:
        need(image[start:end] == bytes(end-start), 'candidate_not_zero')
        need(not any(start <= value < end and kind != 'A'
                     for value,kind,_ in records), 'candidate_symbol')
    for offset in range(named['_rela_start'],named['_rela_end'],24):
        destination,kind,addend = struct.unpack_from('<QQQ',image,offset)
        need(kind == 1027, 'unsupported_relocation')
        need(not any(start <= destination < end or start <= addend < end
                     for start,end in ranges), 'candidate_relocation')
    direct_hits=[]
    for pc in range(named['_text_start'],named['_text_size'],4):
        instruction=audit.word(image,pc)
        target=None
        if instruction & 0x7c000000 == 0x14000000:  # B/BL
            target=pc+audit.signed(instruction&0x3ffffff,26)*4
        elif (instruction & 0xff000010 == 0x54000000 or  # B.cond
              instruction & 0x7e000000 == 0x34000000 or  # CBZ/CBNZ
              instruction & 0x3b000000 == 0x18000000):  # LDR literal
            target=pc+audit.signed((instruction>>5)&0x7ffff,19)*4
        elif instruction & 0x7e000000 == 0x36000000:  # TBZ/TBNZ
            target=pc+audit.signed((instruction>>5)&0x3fff,14)*4
        if target is not None and any(start <= target < end for start,end in ranges):
            direct_hits.append((pc,target))
        kind=instruction & 0x9f000000
        if kind not in (0x10000000,0x90000000):
            continue
        immediate=audit.signed(((instruction>>5)&0x7ffff)<<2 | ((instruction>>29)&3),21)
        if kind == 0x10000000:
            target=pc+immediate
        else:
            # ADRP alone names a page also containing valid entry code. Check
            # a directly adjacent ADD of the same register for a precise address.
            following=audit.word(image,pc+4)
            register=instruction&31
            addend=adjacent_add_offset(following,register)
            if addend is None:
                continue
            target=(pc&~4095)+(immediate<<12)+addend
        if any(start <= target < end for start,end in ranges):
            direct_hits.append((pc,target))
    need(not direct_hits, 'candidate_direct_address')
    need(audit.word(image,ENTRY) == ORIGINAL_MOV and
         audit.bl_target(image,RESUME) == named['debug_putc'] and
         audit.word(image,named['debug_putc']) == 0xd65f03c0,
         'replay_path_changed')
    need([audit.word(image,pc) for pc in (0x904,0x908)] ==
         [0xd5384248,0xf100311f], 'flags_liveness_changed')
    return {'zero_padding':True, 'no_allocated_symbols':True,
            'no_relative_references':True,'no_adr_or_adjacent_adrp_add_references':True,
            'no_direct_branch_or_literal_references':True,
            'computed_reference_proof':False,
            'hook_and_stub_in_same_4k_page':ENTRY//4096 == CODE_START//4096 == (CODE_END-1)//4096,
            'replay_and_next_flag_definition_verified':True}


def build(image, symbols):
    audited=audit.audit(image,symbols)
    layout=region_audit(image,symbols)
    recorder,labels=program()
    entry=struct.pack('<I',branch(ENTRY,CODE_START))
    plan={
        'schema':1,'kind':'smp31e_original_recorder_offline_proposal',
        'native_deployment_ready':False,'entry_authorized':False,
        'input_image_sha256':audited['image_sha256'],
        'input_symbol_sha256':audited['symbol_sha256'],
        'source_sha256':hashlib.sha256((HERE/'recorder.S').read_bytes()).hexdigest(),
        'entry_offset':hex(ENTRY),'resume_offset':hex(RESUME),
        'recorder_offset':hex(CODE_START),'recorder_bytes':len(recorder),
        'recorder_sha256':hashlib.sha256(recorder).hexdigest(),
        'entry_original_word':hex(ORIGINAL_MOV),'entry_branch_word':hex(struct.unpack('<I',entry)[0]),
        'record_range':[hex(RECORD),hex(RECORD_END)],
        'record_fields':{'phase':0,'current_el':8,'mpidr_low24':16,'sctlr_selected_el':24},
        'phase_meaning':{'0':'not_observed','1':'cpu1_identity_recorded',
                         '2':'before_selected_sctlr_read','3':'register_sample_complete',
                         '255':'unsupported_current_el'},
        'clobbers':['x0','x8','NZCV'],'sp_changed':False,'lr_changed':False,
        'ordinary_cpu1_stack_top_offset':'0x178000','labels':{k:hex(v) for k,v in labels.items()},
        'layout_audit':layout,
        'required_before_native':['Independent guest assembly byte match',
            'Instruction-level liveness/replay/exception-path equivalence tests',
            'Read-only proof of existing CPU0 alias permissions and hardware protections',
            'Reviewed cross-core code publication including write alias and fetch alias',
            'Dedicated live review and allowance; no security/firmware/RVBAR changes'],
        'native_execution':'NOT RUN',
    }
    return plan,recorder,entry


def write_outputs(directory, plan, recorder, entry):
    outputs={'recorder.bin':recorder,'entry-branch.bin':entry,
             'plan.json':(json.dumps(plan,indent=2)+'\n').encode('utf-8')}
    try:
        directory=Path(directory).resolve()
        allowed=HERE/'out'
        need(directory == allowed or allowed in directory.parents,
             'output_must_be_owned_ignored_out')
        directory.mkdir(parents=True,exist_ok=True)
        # Check every leaf before creating/writing even the first temporary.
        # lstat deliberately does not follow links, including dangling links.
        for name in outputs:
            try:
                mode=(directory/name).lstat().st_mode
            except FileNotFoundError:
                continue
            need(not stat.S_ISLNK(mode), 'output_leaf_symlink')
            need(stat.S_ISREG(mode), 'output_leaf_not_regular')
        for name,payload in outputs.items():
            descriptor=None
            temporary=None
            try:
                descriptor,temporary=tempfile.mkstemp(prefix='.recorder-',suffix='.tmp',
                                                       dir=directory)
                os.fchmod(descriptor,0o600)
                stream=os.fdopen(descriptor,'wb')
                descriptor=None
                with stream:
                    stream.write(payload)
                    stream.flush()
                    os.fsync(stream.fileno())
                # Replace the directory entry, never write through an existing
                # hardlink (or a symlink introduced after the initial checks).
                os.replace(temporary,directory/name)
                temporary=None
            finally:
                if descriptor is not None:
                    os.close(descriptor)
                if temporary is not None:
                    try:
                        os.unlink(temporary)
                    except FileNotFoundError:
                        pass
    except (OSError, RuntimeError):
        raise ValueError('output_write_failed') from None


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--image',type=Path,required=True)
    parser.add_argument('--symbols',type=Path,required=True)
    parser.add_argument('--out',type=Path,default=HERE/'out')
    args=parser.parse_args()
    plan,recorder,entry=build(args.image.read_bytes(),args.symbols.read_bytes())
    write_outputs(args.out,plan,recorder,entry)
    print(json.dumps({'result':'OFFLINE_RECORDER_PROPOSAL_BUILT',
                      'native_deployment_ready':False,'recorder_bytes':len(recorder),
                      'recorder_sha256':plan['recorder_sha256']}))
